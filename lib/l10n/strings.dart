import '../core/prefs.dart';

/// Tiny translation layer (English + Hindi). No code generation: add a key to both maps and call `tr('key')`.
/// Any key missing in Hindi falls back to English, so screens never show a blank label.
/// Wrap screens in a `ValueListenableBuilder` on `AppPrefs.I.language` (the app root already does) to refresh on change.
String tr(String key, [Map<String, String> vars = const {}]) {
  final lang = AppPrefs.I.language.value;
  var s = (lang == 'hi' ? _hi[key] : null) ?? _en[key] ?? key;
  vars.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

